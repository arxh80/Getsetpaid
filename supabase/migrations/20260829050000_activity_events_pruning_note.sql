-- WHAT IS TRUE
-- ===========================================================================
-- THREE BRANCHES PROJECT A COLUMN, NOT A LITERAL:
--
--     20260829040000:238   merge_absorbed    m.entity_type
--     20260829040000:269   merge_into        m.entity_type
